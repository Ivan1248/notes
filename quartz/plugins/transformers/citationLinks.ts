import { Element, ElementContent, Root, Text } from "hast"
import { visit } from "unist-util-visit"
import { QuartzTransformerPlugin } from "../types"
// @ts-ignore
import citationPopoverScript from "../../components/scripts/citationPopover.inline"

const URL_REGEX = /https?:\/\/[^\s<>"]+/g
// Trailing punctuation that ends the sentence rather than the URL
const TRAILING_PUNCTUATION = /[.,;:!?]+$/

function trimUrl(url: string): string {
  url = url.replace(TRAILING_PUNCTUATION, "")
  // Drop a closing parenthesis that has no opening one inside the URL
  while (url.endsWith(")") && (url.match(/\(/g) ?? []).length < (url.match(/\)/g) ?? []).length) {
    url = url.slice(0, -1).replace(TRAILING_PUNCTUATION, "")
  }
  return url
}

function linkify(text: Text): ElementContent[] {
  const nodes: ElementContent[] = []
  let last = 0
  for (const match of text.value.matchAll(URL_REGEX)) {
    const url = trimUrl(match[0])
    const start = match.index!
    if (start > last) nodes.push({ type: "text", value: text.value.slice(last, start) })
    nodes.push({
      type: "element",
      tagName: "a",
      properties: { href: url, className: ["external"], rel: ["noopener", "noreferrer"] },
      children: [{ type: "text", value: url }],
    })
    last = start + url.length
  }
  if (last === 0) return [text]
  if (last < text.value.length) nodes.push({ type: "text", value: text.value.slice(last) })
  return nodes
}

/**
 * Makes URLs in bibliography entries generated by the Citations plugin clickable, and shows the
 * referenced bibliography entry in a popover when hovering over a citation.
 *
 * Add it after Plugin.Citations, with `linkCitations: true` there.
 */
export const CitationLinks: QuartzTransformerPlugin = () => ({
  name: "CitationLinks",
  htmlPlugins() {
    return [
      () => (tree: Root) => {
        visit(tree, "element", (node: Element) => {
          if (!(node.properties?.className as string[] | undefined)?.includes("csl-entry")) return
          // Entries' existing links are left alone; URLs in all other text become links
          visit(node, "element", (child: Element) => {
            if (child.tagName === "a") return "skip"
            child.children = child.children.flatMap((c) => (c.type === "text" ? linkify(c) : [c]))
          })
          return "skip"
        })
      },
    ]
  },
  externalResources() {
    return {
      js: [{ script: citationPopoverScript, loadTime: "afterDOMReady", contentType: "inline" }],
    }
  },
})
